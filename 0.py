# -*- coding: utf-8 -*-
import math

def gradient_cat():
    print('\033[2J\033[H')  # Очистка экрана
    
    cats = [
        " /^--^\\     /^--^\\     /^--^\\",
        " \\____/     \\____/     \\____/",
        "/      \\   /      \\   /      \\",
        "|       |   |       |   |       |",
        "\\__  __/   \\__  __/   \\__  __/",
        "|^|^|^|^|^|^|^|^|^|^|^|^\\ \\^|^|^|^/ /^|^|^|^|^\\ \\^|^|^|^|^|^|^|^|^|^|^|^|",
        "| | | | | | | | | | | | |\\ \\| | |/ /| | | | | | \\ \\ | | | | | | | | | | |",
        "########################/ /######\\ \\###########/ /#######################",
        "| | | | | | | | | | | | \\/| | | | \\/| | | | | |\\/ | | | | | | | | | | | |",
        "|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|_|"
    ]
    
    for y, line in enumerate(cats):
        # Создаем плавный градиент
        r = int(255 * abs(math.sin(y * 0.5)))
        g = int(255 * abs(math.sin(y * 0.5 + 2)))
        b = int(255 * abs(math.sin(y * 0.5 + 4)))
        
        color = f'\033[38;2;{r};{g};{b}m'
        reset = '\033[0m'
        
        print(color + line + reset)

gradient_cat()
